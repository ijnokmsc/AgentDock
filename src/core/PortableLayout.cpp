// 注意: 判断 junction 不能用 std::filesystem::exists ——
//   * 断链的 junction: exists() == false, 但目录项确实占着名字,
//     此时 mklink 会报「已存在」, 必须先删。
//   * 更危险的是 remove_all(): 它会**递归进目标**把 data\ 里
//     真实数据删干净。对 junction 只能 RemoveDirectoryW (只删链接本身)。
bool entryExists(const fs::path& p) {
    return GetFileAttributesW(p.c_str()) != INVALID_FILE_ATTRIBUTES;
}

bool isReparsePoint(const fs::path& p) {
    DWORD a = GetFileAttributesW(p.c_str());
    return a != INVALID_FILE_ATTRIBUTES && (a & FILE_ATTRIBUTE_REPARSE_POINT) != 0;
}

bool isRealDirectory(const fs::path& p) {
    DWORD a = GetFileAttributesW(p.c_str());
    if (a == INVALID_FILE_ATTRIBUTES) return false;
    if ((a & FILE_ATTRIBUTE_REPARSE_POINT) != 0) return false;   // 是链接, 不算
    return (a & FILE_ATTRIBUTE_DIRECTORY) != 0;
}

bool dirIsEmpty(const fs::path& p) {
    std::error_code ec;
    return fs::directory_iterator(p, ec) == fs::directory_iterator();
}

// 只删目录项本身 (junction / 空目录), 绝不递归
bool removeEntryOnly(const fs::path& p) {
    if (RemoveDirectoryW(p.c_str())) return true;
    std::error_code ec;
    fs::remove(p, ec);
    return !ec;
}

fs::path comSpecPath() {
    wchar_t buf[MAX_PATH] = {0};
    DWORD n = GetEnvironmentVariableW(L"ComSpec", buf, MAX_PATH);
    if (n == 0 || n >= MAX_PATH) return L"C:\\Windows\\System32\\cmd.exe";
    return fs::path(std::wstring(buf, n));
}

bool resolvesTo(const fs::path& link, const fs::path& want) {
    std::error_code ec;
    fs::path a = fs::weakly_canonical(link, ec);
    if (ec || a.empty()) return false;
    std::error_code ec2;
    fs::path b = fs::weakly_canonical(want, ec2);
    if (ec2 || b.empty()) return false;
    return a == b;
}

